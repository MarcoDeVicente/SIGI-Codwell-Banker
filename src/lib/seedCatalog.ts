function buildCitySeedProperties(
  specs: typeof QRO_CATALOG_SPECS,
  prefix: "MX-QRO-2025" | "MX-NL-2025" | "MX-CDMX-2025" | "MX-QR-2025",
  idPrefix: string,
  zone: SeedPropertyRecord["zone"],
  cityAdvisors: SeedAdvisorRecord[],
  imgOffset: number
): SeedPropertyRecord[] {
  return specs.map((item, idx) => {
    const seq = 101 + idx;
    const folio = `${prefix}-${seq}`;
    const adv = cityAdvisors[idx % cityAdvisors.length];
    const image =
      ARCHITECTURAL_UNSPLASH_IMAGES[
        (idx + imgOffset) % ARCHITECTURAL_UNSPLASH_IMAGES.length
      ];
    const typo = item.typology || TYPOLOGIES[idx % TYPOLOGIES.length];

    return {
      id: `${idPrefix}-${seq}`,
      folio,
      title: item.title,
      location: item.location,
      zone,
      typology: typo,
      sale_price: item.salePrice,
      rent_price: item.rentPrice,
      land_area_m2: item.land,
      construction_area_m2: item.constArea,
      bedrooms: item.beds,
      bathrooms: item.baths,
      parking: item.parking,
      ai_match_score: item.match,
      plusvalia_anual: item.plusvalia,
      cap_rate: item.capRate,
      is_exclusive: item.exclusive,
      image_url: image,
      advisorName: adv.fullName,
      advisorEmail: adv.email,
      created_at: new Date(
        Date.UTC(2025, 0, 15, 10, idx % 60, 0)
      ).toISOString(),
    };
  });
}

